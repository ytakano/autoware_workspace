"""Generate the paper's LaTeX tables from the frozen measurement JSONs (stdlib-only).

Inputs (paper/data/): wcet.json (replay timing, both engines), wcet_rust.json (counters),
wcet_alloc.json (LD_PRELOAD allocation pass); optionally wcet_psweep.json + psweep_rust.json
(the P-sweep replay + counters).
Outputs (paper/tables/): counters.tex, tails.tex, alloc.tex, regression.tex;
prose-macro files (*_macros.tex: tails, regression, legal, realdata, psweep, env,
subnormal A/B) so no measurement number is ever hand-typed in the .tex sources; with psweep data
also tables/psweep.tex and figures/psweep.tex (pgfplots).

Regenerate after any re-measurement:  python3 scripts/gen_tables.py
Never hand-edit tables/*.tex or figures/*.tex — they are build products (kept in git so the
paper builds without re-running the benchmark).

The generator also checks the numerical and qualitative invariants consumed by the prose.
Generation fails when the measurements no longer support a stated claim.
wcet.json must carry the Isolated meta.manifest emitted by scripts/integrate_campaign.py.
"""

