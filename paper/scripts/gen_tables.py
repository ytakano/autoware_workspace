    if rust_doc.get("meta", {}).get("engine_commit") != host_meta["engine_commit"]:
        raise SystemExit("psweep: deterministic counters and host snapshot use different commits")
    timing_commit = timing_doc["meta"]["manifest"].get("rust_commit")
