def pct(sorted_xs, p):
    return sorted_xs[min(int(p * (len(sorted_xs) - 1)), len(sorted_xs) - 1)]


def num(x):
    """LaTeX-format an integer with thin-space thousands separators via siunitx."""
    return rf"\num{{{x}}}"


def write(name, caption, label, colspec, header, rows, note=None, tabcolsep="4pt",
          size=r"\footnotesize"):
    lines = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        size,
        rf"\setlength{{\tabcolsep}}{{{tabcolsep}}}",
        rf"\begin{{tabular}}{{{colspec}}}",
        r"\toprule",
        header + r" \\",
        r"\midrule",
    ]
    lines += [r + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    if note:
        lines.append(rf"\par\smallskip\footnotesize {note}")
    lines.append(r"\end{table}")
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote tables/{name}")


def tex_escape(s):
    """Escape the characters that actually occur in the env strings."""
    return s.replace("~", r"\textasciitilde{}").replace("_", r"\_")


def provenance(manifest, meta):
    """One generated sentence carried by every timing-table note.

    Built from the policy-schema meta.manifest of the campaign integration; names the
    measurement configuration so no table can be read without its protocol.
    """
    sessions = manifest.get("sessions") or [manifest.get("experiment_id", "?")]
    dates = sorted({m["run_timestamp"][:10]
                    for m in manifest.get("session_manifests", [manifest])})
    configuration = {"A": "Replay", "B": "Isolated"}.get(
        manifest["measurement_profile"], manifest["measurement_profile"])
    session_count = len(sessions)
    session_word = "session" if session_count == 1 else "sessions"
    sample_count = meta.get("pooled_samples_per_fixture", meta["iters"])
    return (
        rf"{configuration}: {session_count} {session_word}, {'/'.join(dates)}, "
        rf"isolated pinned core "
        rf"(\texttt{{{tex_escape(manifest.get('affinity_mask', '?'))}}}), "
        rf"{sample_count} measured aligns per fixture and engine."
    )


def kernel_disp(v):
    """'Linux <hostname> <release>' -> 'Linux <release>' for display."""
    parts = v.split()
    return f"{parts[0]} {parts[-1]}" if len(parts) == 3 else v


def env_macros(manifest, meta):
    """Measurement-environment macros checked against the recorded data."""
    cv = manifest.get("compiler_versions") or {}
    flags = manifest.get("compiler_flags") or {}
    if flags.get("CMAKE_BUILD_TYPE") != "Release":
        raise SystemExit("env: expected CMAKE_BUILD_TYPE=Release")
    if flags.get("CMAKE_CXX_FLAGS_RELEASE") != "-O3 -DNDEBUG":
        raise SystemExit("env: expected CMAKE_CXX_FLAGS_RELEASE=-O3 -DNDEBUG")
    if flags.get("NDT_BUILD_TRACED") != "OFF":
        raise SystemExit("env: timing data must use NDT_BUILD_TRACED=OFF")
    if manifest.get("cargo_profile") != "[profile.release]\noverflow-checks = true":
        raise SystemExit("env: unexpected Cargo release profile")
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\envCpu}}{{{tex_escape(manifest.get('cpu_model') or '?')}}}",
        rf"\newcommand{{\envKernel}}{{{tex_escape(kernel_disp(manifest.get('kernel_version') or '?'))}}}",
        rf"\newcommand{{\envCppCompiler}}{{{tex_escape(cv.get('cxx') or '?')}}}",
        rf"\newcommand{{\envRustCompiler}}{{{tex_escape(cv.get('rustc') or '?')}}}",
        r"\newcommand{\envCppReleaseFlags}{\texttt{-O3 -DNDEBUG}}",
        rf"\newcommand{{\envGovernor}}{{{manifest.get('governor') or '?'}}}",
        rf"\newcommand{{\envWarmup}}{{{meta['warmup']}}}",
        rf"\newcommand{{\envSessions}}{{{len(manifest.get('sessions', [1]))}}}",
    ]
    n_sessions = len(manifest.get("sessions", [1]))
    required = ("samples_per_session", "pooled_samples_per_fixture", "session_count")
    missing = [key for key in required if key not in meta]
    if missing:
        raise SystemExit(f"env: structured sample metadata missing {missing}")
    if int(meta["session_count"]) != n_sessions:
        raise SystemExit("env: structured session count disagrees with the manifest")
    per_session = str(meta["samples_per_session"])
    pooled = str(meta["pooled_samples_per_fixture"])
    macros += [
        rf"\newcommand{{\envSamplesPerSession}}{{{per_session}}}",
        rf"\newcommand{{\envPooledSamples}}{{{pooled}}}",
        rf"\newcommand{{\envCommit}}{{{(manifest.get('cpp_commit') or '?')[:8]}}}",
    ]
    (OUT / "env_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/env_macros.tex")


def runtime_limits_macros():
    """Validate the declared work envelope and generate its prose macros."""
    doc = json.loads((DATA / "runtime_limits.json").read_text())
    source = doc["source_points"]
    leaves = doc["active_leaves"]
    replay = doc["validation_replay"]

    p_observed = int(source["observed_max"])
    p_limit = int(source["configured_limit"])
    leaves_observed = int(leaves["full_map_epoch_observed"])
    margin = float(leaves["margin_percent"])
    unrounded = float(leaves["unrounded_limit"])
    leaves_limit = int(leaves["configured_limit"])
    scratch = int(doc["serial_scratch_payload_bytes"])
    iteration_limit = 30
    neighbor_limit = 64
    kernel_max = (iteration_limit + 1) * p_limit * neighbor_limit
    kd_max = (iteration_limit + 1) * p_limit * leaves_limit
    expected_unrounded = leaves_observed * (1.0 + margin / 100.0)

    if p_observed <= 0 or p_limit < p_observed:
        raise SystemExit("runtime limits: source-point limit does not cover the replay maximum")
    if leaves_observed <= 0 or leaves_limit < unrounded:
        raise SystemExit("runtime limits: leaf limit does not include the declared margin")
    if not math.isclose(unrounded, expected_unrounded, rel_tol=0.0, abs_tol=0.05):
        raise SystemExit("runtime limits: recorded unrounded leaf limit disagrees with its margin")
    if scratch <= 0:
        raise SystemExit("runtime limits: scratch capacity must be positive")
    if int(replay["observed_max_neighbors"]) > 64:
        raise SystemExit("runtime limits: validation replay exceeds the neighbor cap")

    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\runtimePMax}}{{{p_limit}}}",
        rf"\newcommand{{\runtimeLeavesObserved}}{{{leaves_observed}}}",
        rf"\newcommand{{\runtimeLeavesMax}}{{{leaves_limit}}}",
        rf"\newcommand{{\runtimeScratchBytes}}{{{scratch}}}",
        rf"\newcommand{{\runtimeKernelEvalMax}}{{\num{{{kernel_max}}}}}",
        rf"\newcommand{{\runtimeKdVisitMax}}{{\num{{{kd_max}}}}}",
        rf"\newcommand{{\runtimeValidationFrames}}{{{int(replay['frames'])}}}",
        rf"\newcommand{{\runtimeObservedKMax}}{{{int(replay['observed_max_neighbors'])}}}",
        rf"\newcommand{{\runtimeNeighborLimitFrames}}{{{int(replay['neighbor_limit_frames'])}}}",
    ]
    (OUT / "runtime_limits_macros.tex").write_text(
        "\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/runtime_limits_macros.tex")


