    def reg_features(row, nterms):
        pts, nbr, kd, _t, _n = row
        return (pts, nbr, kd, 1.0) if nterms == 4 else (nbr, kd, 1.0)

    def fit(rows_, nterms):
        k = 4 if nterms == 4 else 3
        ata = [[0.0] * k for _ in range(k)]
        atb = [0.0] * k
        for row in rows_:
            x = reg_features(row, nterms)
            t = row[3]
            for i in range(k):
                for j in range(k):
                    ata[i][j] += x[i] * x[j]
                atb[i] += x[i] * t
        m = [ata[i][:] + [atb[i]] for i in range(k)]
        for col in range(k):
            piv = max(range(col, k), key=lambda r: abs(m[r][col]))
            m[col], m[piv] = m[piv], m[col]
            for r in range(k):
                if r != col:
                    f = m[r][col] / m[col][col]
                    for cc in range(col, k + 1):
                        m[r][cc] -= f * m[col][cc]
        coef = [m[i][k] / m[i][i] for i in range(k)]

        def pred(row):
            return sum(c * v for c, v in zip(coef, reg_features(row, nterms)))

        mean_t = sum(r[3] for r in rows_) / len(rows_)
        ss_tot = sum((r[3] - mean_t) ** 2 for r in rows_)
        ss_res = sum((r[3] - pred(r)) ** 2 for r in rows_)
        return coef, 1.0 - ss_res / ss_tot, pred

    def loo_stats(rows_, nterms):
        errs = []
        for i in range(len(rows_)):
            _c2, _r2, pred2 = fit(rows_[:i] + rows_[i + 1 :], nterms)
            errs.append(
                (100.0 * abs(pred2(rows_[i]) - rows_[i][3]) / rows_[i][3], rows_[i][4])
            )
        errs.sort()
        return errs[len(errs) // 2][0], errs[-1][0], errs[-1][1]

    def boot_cis(rows_, nterms):
        rng = random.Random(20260712)
        k = 4 if nterms == 4 else 3
        boots = [[] for _ in range(k)]
        n_ = len(rows_)
        for _ in range(2000):
            sample = [rows_[rng.randrange(n_)] for _ in range(n_)]
            try:
                coef, _, _ = fit(sample, nterms)
            except ZeroDivisionError:
                continue  # degenerate resample
            for i in range(k):
                boots[i].append(coef[i])
        cis = []
        for xs in boots:
            xs.sort()
            cis.append((xs[int(0.025 * len(xs))], xs[int(0.975 * len(xs))]))
        return cis

    # Engine-specific adopted model (guarded so generation fails if the data stops
    # supporting the adopted engine-specific asymmetry).
    REG_SELECTED = {"cpp": 4, "rust": 2}
    rows = []
    reg_macros = ["% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit."]
