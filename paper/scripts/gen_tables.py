def main():
    doc = json.loads((DATA / "wcet.json").read_text())
    timing = doc["fixtures"]
    env = doc.get("env", {})
    meta = doc.get("meta", {})
    rust = json.loads((DATA / "wcet_rust.json").read_text())["fixtures"]
    alloc = json.loads((DATA / "wcet_alloc.json").read_text())["fixtures"]
    names = [n for n in ORDER if n in timing]
    prov = provenance(env, meta)
    env_macros(env, meta)
    oneoff_macros()

    # ---- counters.tex ----
    rows = []
    for n in names:
        c = rust[n]["counters"]
        rows.append(
            f"{LABEL[n]} & {rust[n]['iteration_num']} & {num(c['sum_neighbors'])} "
            f"& {num(c['kd_nodes_visited'])} & {num(rust[n]['n_map'])} & {rust[n]['n_tiles']}"
        )
    write(
        "counters.tex",
        r"Frozen fixtures: deterministic work counters (platform-independent; "
        r"$P=2000$ for the search outputs).",
        "tab:counters",
        "lrrrrr",
        r"fixture & $N_{\mathrm{iter}}$ & \sumnbr{} & \kdnodes{} & map pts & tiles",
        rows,
        note=r"$\sumnbr = \num{3968000} = 2000 \cdot 64 \cdot 31$ on "
        r"\emph{search-00}: the analytic kernel-evaluation maximum, reached exactly. " + TIER_NOTE,
    )

    # ---- tails.tex ----
    rows = []
    ratios = {}
    p50 = {}  # (fixture, engine) -> p50 ms
    mx = {}  # (fixture, engine) -> max ms
    for n in names:
        fx = timing[n]
        cs = sorted(fx["cpp"]["samples_ms"])
        rs = sorted(fx["rust"]["samples_ms"])
        p50[(n, "cpp")], p50[(n, "rust")] = pct(cs, 0.5), pct(rs, 0.5)
        mx[(n, "cpp")], mx[(n, "rust")] = cs[-1], rs[-1]
        ratios[n] = rs[-1] / cs[-1]
        rows.append(
            f"{LABEL[n]} & {pct(cs, 0.5):.1f} & {cs[-1]:.1f} & {pct(rs, 0.5):.1f} "
            f"& {rs[-1]:.1f} & \\textbf{{{ratios[n]:.2f}}}"
        )
    write(
        "tails.tex",
        rf"Frame time per engine (\si{{ms}}; {meta['iters']} aligns/fixture, serial, "
        r"pinned core). Equal work certified per fixture (identical "
        r"\texttt{iteration\_num}).",
        "tab:tails",
        "lrrrrr",
        r"fixture & \multicolumn{2}{c}{C++ (p50 / max)} "
        r"& \multicolumn{2}{c}{Rust (p50 / max)} & ratio",
        rows,
        note=r"ratio = Rust max / C++ max; $<1$ everywhere. " + TIER_NOTE + " " + prov,
    )

    # ---- tails_macros.tex: timing/counter/alloc-derived prose numbers ----
    # Per-point-per-pass cost (us) on the neighbor-sparse fixtures; points_processed
    # already equals passes * P.
    def pt_pass_us(n, eng):
        return p50[(n, eng)] * 1000.0 / rust[n]["counters"]["points_processed"]

    def kbar_of(n):
        c = rust[n]["counters"]
        return c["sum_neighbors"] / c["points_processed"]

    gap_sub = pt_pass_us("subnormal", "cpp") - pt_pass_us("subnormal", "rust")
    gap_ch = pt_pass_us("cache_hostile", "cpp") - pt_pass_us("cache_hostile", "rust")
    # "reappears as the same constant on cache-hostile": the two gaps must stay close.
    if abs(gap_sub - gap_ch) > 0.15 * gap_sub:
        raise SystemExit(
            f"per-point overhead gap diverged (subnormal {gap_sub:.2f} vs "
            f"cache-hostile {gap_ch:.2f} us) -- prose claims 'the same constant'"
        )
    # Allocator share of the gap: ONEOFF fast-path pair cost x measured pairs per pt-pass.
    sub_pairs = alloc["subnormal"]["cpp"]["allocs_per_align"] / rust["subnormal"]["counters"][
        "points_processed"
    ]
    alloc_share = 100.0 * ONEOFF["malloc_pair_ns"] * sub_pairs / (gap_sub * 1000.0)
    # search-00 kd term and its growth over the ONEOFF search-log gen-0 baseline.
    kd_m = rust["search_00"]["counters"]["kd_nodes_visited"] / 1e6
    if abs(kd_m - 12.01) > 0.005:
        raise SystemExit(
            f"search-00 kd = {kd_m:.2f} M: fixture changed; the ONEOFF kd_gen_zero_m "
            "search-log baseline (and the derived growth %) no longer applies"
        )
    kd_growth = 100.0 * (kd_m / ONEOFF["kd_gen_zero_m"] - 1.0)
    # Two-tier kernel-evaluation drop.
    nbr_search = rust["search_00"]["counters"]["sum_neighbors"]
    nbr_legal = rust["legal_worst"]["counters"]["sum_neighbors"]
    # Alloc headline: worst fixture per align, and the per-(pt.pass) constant.
    alloc_worst = max(alloc[n]["cpp"]["allocs_per_align"] for n in names)
    app = alloc["search_00"]["cpp"]["allocs_per_align"] / rust["search_00"]["counters"][
        "points_processed"
    ]
    # "under 10 ms to over 600 ms" (intro spread claim).
    if not (min(p50.values()) < 10.0 and mx[("search_00", "cpp")] > 600.0
            and mx[("search_00", "rust")] > 600.0):
        raise SystemExit("intro spread claim (under 10 ms to over 600 ms) is stale")
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\tailsRatioMin}}{{{min(ratios.values()):.2f}}}",
        rf"\newcommand{{\tailsRatioMax}}{{{max(ratios.values()):.2f}}}",
        rf"\newcommand{{\tailsSearchMaxCpp}}{{{mx[('search_00', 'cpp')]:.1f}}}",
        rf"\newcommand{{\tailsSearchMaxRust}}{{{mx[('search_00', 'rust')]:.1f}}}",
        rf"\newcommand{{\subnormalMedianRatio}}{{{p50[('subnormal', 'cpp')] / p50[('subnormal', 'rust')]:.1f}}}",
        rf"\newcommand{{\subnormalPtPassCppUs}}{{{pt_pass_us('subnormal', 'cpp'):.1f}}}",
        rf"\newcommand{{\subnormalPtPassRustUs}}{{{pt_pass_us('subnormal', 'rust'):.2f}}}",
        rf"\newcommand{{\ptPassGapUs}}{{{gap_sub:.1f}}}",
        rf"\newcommand{{\subnormalKbar}}{{{kbar_of('subnormal'):.1f}}}",
        rf"\newcommand{{\cacheHostileKbar}}{{{kbar_of('cache_hostile'):.1f}}}",
        rf"\newcommand{{\subnormalAllocPairs}}{{{sub_pairs:.0f}}}",
        rf"\newcommand{{\subnormalAllocSharePct}}{{{alloc_share:.0f}}}",
        rf"\newcommand{{\searchZeroKdM}}{{{kd_m:.2f}}}",
        rf"\newcommand{{\searchKdGrowthPct}}{{{kd_growth:.0f}}}",
        rf"\newcommand{{\searchZeroSumNbrM}}{{{nbr_search / 1e6:.2f}}}",
        rf"\newcommand{{\legalWorstSumNbrK}}{{{nbr_legal / 1e3:.0f}}}",
        rf"\newcommand{{\twoTierKernelDrop}}{{{nbr_search / nbr_legal:.1f}}}",
        rf"\newcommand{{\allocWorstPerAlign}}{{\num{{{alloc_worst}}}}}",
        rf"\newcommand{{\allocPerPtPass}}{{{app:.0f}}}",
        rf"\newcommand{{\allocPerPtPassExact}}{{{app:.1f}}}",
    ]
    (OUT / "tails_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/tails_macros.tex")

    # ---- alloc.tex ----
    rows = []
    for n in names:
        fx = alloc[n]
        c = rust[n]["counters"]
        per_pp = fx["cpp"]["allocs_per_align"] / (
            c["derivative_passes"] * rust[n]["n_source"]
        )
        rows.append(
            f"{LABEL[n]} & {num(fx['cpp']['allocs_per_align'])} & {per_pp:.1f} "
            f"& {fx['rust']['allocs_per_align']}"
        )
    write(
        "alloc.tex",
        r"Heap allocations per align (\texttt{LD\_PRELOAD} interposer).",
        "tab:alloc",
        "lrrr",
        r"fixture & C++ / align & C++ / (pt$\cdot$pass) & Rust / align",
        rows,
        note=r"The constant ${\approx}11$ per point per pass locates the source in the "
        r"per-point inner loop (Sec.~\ref{sec:eval-alloc}). Rust: zero, matching the "
        r"allocation-freedom proof. " + TIER_NOTE + " " + prov,
    )

    # ---- regression.tex ----
    def fit(engine):
        rows_ = []
        for n in names:
            c = rust[n]["counters"]
            t50 = pct(sorted(timing[n][engine]["samples_ms"]), 0.5)
            rows_.append((float(c["sum_neighbors"]), float(c["kd_nodes_visited"]), t50))
        ata = [[0.0] * 3 for _ in range(3)]
        atb = [0.0] * 3
        for nbr, kd, t in rows_:
            x = (nbr, kd, 1.0)
            for i in range(3):
                for j in range(3):
                    ata[i][j] += x[i] * x[j]
                atb[i] += x[i] * t
        m = [row[:] + [atb[i]] for i, row in enumerate(ata)]
        for col in range(3):
            piv = max(range(col, 3), key=lambda r: abs(m[r][col]))
            m[col], m[piv] = m[piv], m[col]
            for r in range(3):
                if r != col:
                    f = m[r][col] / m[col][col]
                    for cc in range(col, 4):
                        m[r][cc] -= f * m[col][cc]
        a, b, c0 = (m[i][3] / m[i][i] for i in range(3))
        mean_t = sum(t for _, _, t in rows_) / len(rows_)
        ss_tot = sum((t - mean_t) ** 2 for _, _, t in rows_)
        ss_res = sum((t - (a * nbr + b * kd + c0)) ** 2 for nbr, kd, t in rows_)
        return a, b, c0, 1.0 - ss_res / ss_tot

    rows = []
    reg_macros = ["% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit."]
    reg_a = {}
    for eng, lab in (("cpp", "C++"), ("rust", "Rust")):
        a, b, c0, r2 = fit(eng)
        rows.append(f"{lab} & {a * 1e6:.1f} & {b * 1e6:.1f} & {c0:.2f} & {r2:.4f}")
        cap = eng.capitalize().replace("Cpp", "Cpp")
        cap = "Cpp" if eng == "cpp" else "Rust"
        reg_a[eng] = a
        reg_macros.append(rf"\newcommand{{\regKernelNs{cap}}}{{{a * 1e6:.0f}}}")
        reg_macros.append(rf"\newcommand{{\regKdNs{cap}}}{{{b * 1e6:.0f}}}")
        reg_macros.append(rf"\newcommand{{\regRsq{cap}}}{{{r2:.4f}}}")
    reg_macros.append(
        rf"\newcommand{{\regKernelRatio}}{{{reg_a['cpp'] / reg_a['rust']:.1f}}}"
    )
    (OUT / "regression_macros.tex").write_text("\n".join(reg_macros) + "\n", encoding="utf-8")
    print("wrote tables/regression_macros.tex")
    write(
        "regression.tex",
        rf"Unit-cost regression $T_{{p50}} \approx a\cdot\sumnbr + b\cdot\kdnodes + c$ "
        rf"over the fixture set ($n={len(names)}$).",
        "tab:regression",
        "lrrrr",
        r"engine & $a$ (\si{ns}/kernel eval) & $b$ (\si{ns}/kd node) & $c$ (\si{ms}) & $R^2$",
        rows,
        note=prov,
    )

    # ---- gumbel.tex ----
    def gumbel(xs, block=10):
        maxima = [max(xs[i : i + block]) for i in range(0, len(xs) - block + 1, block)]
        n = len(maxima)
        m = sum(maxima) / n
        s = math.sqrt(sum((x - m) ** 2 for x in maxima) / (n - 1))
        beta = s * math.sqrt(6.0) / math.pi
        return m - EULER_GAMMA * beta, beta

    rows = []
    betas = []
    exceed = {}  # engine -> % the 1e-9 quantile sits above the measured max (search_00)
    for n in names:
        for eng, lab in (("cpp", "C++"), ("rust", "Rust")):
            xs = timing[n][eng]["samples_ms"]
            mu, beta = gumbel(xs)
            q9 = mu - beta * math.log(-math.log(1.0 - 1e-9))
            betas.append(beta)
            if n == "search_00":
                exceed[eng] = 100.0 * (q9 / max(xs) - 1.0)
            first = LABEL[n] if eng == "cpp" else ""
            rows.append(
                f"{first} & {lab} & {mu:.1f} & {beta:.2f} & {q9:.1f} & {max(xs):.1f}"
            )
    write(
        "gumbel.tex",
        r"Gumbel block-maxima fit (moment estimator, $n{=}10$ blocks) and the "
        r"$10^{-9}$ per-block exceedance quantile (\si{ms}). Comparative, not certified "
        r"(Sec.~\ref{sec:threats}).",
        "tab:gumbel",
        "llrrrr",
        r"fixture & engine & $\mu$ & $\beta$ & $q_{10^{-9}}$ & max",
        rows,
        note=prov,
    )
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\gumbelBetaMin}}{{{min(betas):.2f}}}",
        rf"\newcommand{{\gumbelBetaMax}}{{{max(betas):.1f}}}",
        rf"\newcommand{{\gumbelExceedPctCpp}}{{{exceed['cpp']:.0f}}}",
        rf"\newcommand{{\gumbelExceedPctRust}}{{{exceed['rust']:.0f}}}",
    ]
    (OUT / "gumbel_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/gumbel_macros.tex")


def legal_macros(timing, rust):
    """Prose macros for the two-tier bound (skipped when legal_worst is absent)."""
    if "legal_worst" not in timing or "search_00" not in timing:
        print("legal_worst absent -- skipping legal macros")
        return
    lw = timing["legal_worst"]
    un = timing["search_00"]
    c = rust["legal_worst"]["counters"]
    kbar = c["sum_neighbors"] / c["points_processed"]
    lw_cpp = max(lw["cpp"]["samples_ms"])
    lw_rust = max(lw["rust"]["samples_ms"])
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\legalWorstMaxCpp}}{{{lw_cpp:.1f}}}",
        rf"\newcommand{{\legalWorstMaxRust}}{{{lw_rust:.1f}}}",
        rf"\newcommand{{\legalWorstKbar}}{{{kbar:.1f}}}",
        rf"\newcommand{{\legalWorstRatioRust}}{{{max(un['rust']['samples_ms']) / lw_rust:.1f}}}",
        rf"\newcommand{{\legalWorstRatioCpp}}{{{max(un['cpp']['samples_ms']) / lw_cpp:.1f}}}",
    ]
    if "legal_osc" in timing:
        lo = timing["legal_osc"]
        oc = rust["legal_osc"]["counters"]
        macros += [
            rf"\newcommand{{\legalOscMaxCpp}}{{{max(lo['cpp']['samples_ms']):.1f}}}",
            rf"\newcommand{{\legalOscMaxRust}}{{{max(lo['rust']['samples_ms']):.1f}}}",
            rf"\newcommand{{\legalOscKbar}}{{{oc['sum_neighbors'] / oc['points_processed']:.1f}}}",
        ]
    (OUT / "legal_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/legal_macros.tex")


def realdata():
    """Operational-envelope table + macros from the real-drive capture (skipped if absent)."""
    rj = DATA / "realdata.json"
    if not rj.exists():
        print("realdata absent -- skipping operational-envelope outputs")
        return
    allframes = json.loads(rj.read_text())["frames"]
    timing = json.loads((DATA / "wcet.json").read_text())["fixtures"]
    # Envelope rows use the on-map frames (the vehicle leaves the benchmark's cropped map for
    # most of the 57-min bag); P and max-K contract checks use ALL frames.
    frames = [f for f in allframes if f["counters"]["sum_neighbors"] > 0]

    def series(f):
        return sorted(f(x) for x in frames)

    p = sorted(x["n_source"] for x in allframes)
    it = series(lambda x: x["iteration_num"])
