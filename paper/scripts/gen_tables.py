#!/usr/bin/env python3
"""Generate the paper's LaTeX tables from the frozen measurement JSONs (stdlib-only).

Inputs (paper/data/): wcet.json (replay timing, both engines), wcet_rust.json (counters),
wcet_alloc.json (LD_PRELOAD allocation pass); optionally wcet_psweep.json + psweep_rust.json
(the P-sweep replay + counters).
Outputs (paper/tables/): counters.tex, tails.tex, alloc.tex, regression.tex, gumbel.tex;
with psweep data also tables/psweep.tex, tables/psweep_macros.tex (\\psweep* prose macros),
and figures/psweep.tex (pgfplots).

Regenerate after any re-measurement:  python3 scripts/gen_tables.py
Never hand-edit tables/*.tex or figures/*.tex — they are build products (kept in git so the
paper builds without re-running the benchmark).
"""

import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "tables"

EULER_GAMMA = 0.5772156649015329
# Display order: worst first.
ORDER = [
    "search_00",
    "search_01",
    "dense_neighbors",
    "max_iterations",
    "cache_hostile",
    "subnormal",
    "legal_worst",
    "legal_osc",
]
LABEL = {
    "search_00": r"\emph{search-00}",
    "search_01": r"\emph{search-01}",
    "dense_neighbors": r"\emph{dense-nbrs}",
    "max_iterations": r"\emph{max-iters}",
    "cache_hostile": r"\emph{cache-hostile}",
    "subnormal": r"\emph{subnormal}",
    "legal_worst": r"\emph{legal-worst}$^\dagger$",
    "legal_osc": r"\emph{legal-osc}$^\dagger$",
}
# Shared table footnote for the tier markers.
TIER_NOTE = (r"\emph{search-00} is the union-worst search output; "
             r"$^\dagger$\,deployment-tier fixtures.")


def pct(sorted_xs, p):
    return sorted_xs[min(int(p * (len(sorted_xs) - 1)), len(sorted_xs) - 1)]


def num(x):
    """LaTeX-format an integer with thin-space thousands separators via siunitx."""
    return rf"\num{{{x}}}"


def write(name, caption, label, colspec, header, rows, note=None):
    lines = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        rf"\begin{{tabular}}{{{colspec}}}",
        r"\toprule",
        header + r" \\",
        r"\midrule",
    ]
    lines += [r + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    if note:
        lines.append(rf"\par\smallskip\footnotesize {note}")
    lines.append(r"\end{table}")
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote tables/{name}")


def main():
    timing = json.loads((DATA / "wcet.json").read_text())["fixtures"]
    rust = json.loads((DATA / "wcet_rust.json").read_text())["fixtures"]
    alloc = json.loads((DATA / "wcet_alloc.json").read_text())["fixtures"]
    names = [n for n in ORDER if n in timing]

    # ---- counters.tex ----
    rows = []
    for n in names:
        c = rust[n]["counters"]
        rows.append(
            f"{LABEL[n]} & {rust[n]['iteration_num']} & {num(c['sum_neighbors'])} "
            f"& {num(c['kd_nodes_visited'])} & {num(rust[n]['n_map'])} & {rust[n]['n_tiles']}"
        )
    write(
        "counters.tex",
        r"Frozen fixtures: deterministic work counters (platform-independent; "
        r"$P=2000$ for the search outputs).",
        "tab:counters",
        "lrrrrr",
        r"fixture & $N_{\mathrm{iter}}$ & \sumnbr{} & \kdnodes{} & map pts & tiles",
        rows,
        note=r"$\sumnbr = \num{3968000} = 2000 \cdot 64 \cdot 31$ on "
        r"\emph{search-00}: the analytic kernel-evaluation maximum, reached exactly. " + TIER_NOTE,
    )

    # ---- tails.tex ----
    rows = []
    for n in names:
        fx = timing[n]
        cs = sorted(fx["cpp"]["samples_ms"])
        rs = sorted(fx["rust"]["samples_ms"])
        ratio = rs[-1] / cs[-1]
        rows.append(
            f"{LABEL[n]} & {pct(cs, 0.5):.1f} & {cs[-1]:.1f} & {pct(rs, 0.5):.1f} "
            f"& {rs[-1]:.1f} & \\textbf{{{ratio:.2f}}}"
        )
    write(
        "tails.tex",
        r"Frame time per engine (\si{ms}; 100 aligns/fixture, serial, pinned core). "
        r"Equal work certified per fixture (identical \texttt{iteration\_num}).",
        "tab:tails",
        "lrrrrr",
        r"fixture & \multicolumn{2}{c}{C++ (p50 / max)} "
        r"& \multicolumn{2}{c}{Rust (p50 / max)} & ratio",
        rows,
        note=r"ratio = Rust max / C++ max; $<1$ everywhere. " + TIER_NOTE,
    )

    # ---- alloc.tex ----
    rows = []
    for n in names:
        fx = alloc[n]
        c = rust[n]["counters"]
        per_pp = fx["cpp"]["allocs_per_align"] / (
            c["derivative_passes"] * rust[n]["n_source"]
        )
        rows.append(
            f"{LABEL[n]} & {num(fx['cpp']['allocs_per_align'])} & {per_pp:.1f} "
            f"& {fx['rust']['allocs_per_align']}"
        )
    write(
        "alloc.tex",
        r"Heap allocations per align (\texttt{LD\_PRELOAD} interposer).",
        "tab:alloc",
        "lrrr",
        r"fixture & C++ / align & C++ / (pt$\cdot$pass) & Rust / align",
        rows,
        note=r"The constant ${\approx}11$ per point per pass locates the source in the "
        r"per-point inner loop (Sec.~\ref{sec:eval-alloc}). Rust: zero, matching the "
        r"allocation-freedom proof. " + TIER_NOTE,
    )

    # ---- regression.tex ----
    def fit(engine):
        rows_ = []
        for n in names:
            c = rust[n]["counters"]
            t50 = pct(sorted(timing[n][engine]["samples_ms"]), 0.5)
            rows_.append((float(c["sum_neighbors"]), float(c["kd_nodes_visited"]), t50))
        ata = [[0.0] * 3 for _ in range(3)]
        atb = [0.0] * 3
        for nbr, kd, t in rows_:
            x = (nbr, kd, 1.0)
            for i in range(3):
                for j in range(3):
                    ata[i][j] += x[i] * x[j]
                atb[i] += x[i] * t
        m = [row[:] + [atb[i]] for i, row in enumerate(ata)]
        for col in range(3):
            piv = max(range(col, 3), key=lambda r: abs(m[r][col]))
            m[col], m[piv] = m[piv], m[col]
            for r in range(3):
                if r != col:
                    f = m[r][col] / m[col][col]
                    for cc in range(col, 4):
                        m[r][cc] -= f * m[col][cc]
        a, b, c0 = (m[i][3] / m[i][i] for i in range(3))
        mean_t = sum(t for _, _, t in rows_) / len(rows_)
        ss_tot = sum((t - mean_t) ** 2 for _, _, t in rows_)
        ss_res = sum((t - (a * nbr + b * kd + c0)) ** 2 for nbr, kd, t in rows_)
        return a, b, c0, 1.0 - ss_res / ss_tot

    rows = []
    reg_macros = ["% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit."]
    reg_a = {}
    for eng, lab in (("cpp", "C++"), ("rust", "Rust")):
        a, b, c0, r2 = fit(eng)
        rows.append(f"{lab} & {a * 1e6:.1f} & {b * 1e6:.1f} & {c0:.2f} & {r2:.4f}")
        cap = eng.capitalize().replace("Cpp", "Cpp")
        cap = "Cpp" if eng == "cpp" else "Rust"
        reg_a[eng] = a
        reg_macros.append(rf"\newcommand{{\regKernelNs{cap}}}{{{a * 1e6:.0f}}}")
        reg_macros.append(rf"\newcommand{{\regKdNs{cap}}}{{{b * 1e6:.0f}}}")
        reg_macros.append(rf"\newcommand{{\regRsq{cap}}}{{{r2:.4f}}}")
    reg_macros.append(
        rf"\newcommand{{\regKernelRatio}}{{{reg_a['cpp'] / reg_a['rust']:.1f}}}"
    )
    (OUT / "regression_macros.tex").write_text("\n".join(reg_macros) + "\n", encoding="utf-8")
    print("wrote tables/regression_macros.tex")
    write(
        "regression.tex",
        r"Unit-cost regression $T_{p50} \approx a\cdot\sumnbr + b\cdot\kdnodes + c$ "
        r"over the fixture set ($n=6$).",
        "tab:regression",
        "lrrrr",
        r"engine & $a$ (\si{ns}/kernel eval) & $b$ (\si{ns}/kd node) & $c$ (\si{ms}) & $R^2$",
        rows,
    )

    # ---- gumbel.tex ----
    def gumbel(xs, block=10):
        maxima = [max(xs[i : i + block]) for i in range(0, len(xs) - block + 1, block)]
        n = len(maxima)
        m = sum(maxima) / n
        s = math.sqrt(sum((x - m) ** 2 for x in maxima) / (n - 1))
        beta = s * math.sqrt(6.0) / math.pi
        return m - EULER_GAMMA * beta, beta

    rows = []
    for n in names:
        for eng, lab in (("cpp", "C++"), ("rust", "Rust")):
            xs = timing[n][eng]["samples_ms"]
            mu, beta = gumbel(xs)
            q9 = mu - beta * math.log(-math.log(1.0 - 1e-9))
            first = LABEL[n] if eng == "cpp" else ""
            rows.append(
                f"{first} & {lab} & {mu:.1f} & {beta:.2f} & {q9:.1f} & {max(xs):.1f}"
            )
    write(
        "gumbel.tex",
        r"Gumbel block-maxima fit (moment estimator, $n{=}10$ blocks) and the "
        r"$10^{-9}$ per-block exceedance quantile (\si{ms}). Comparative, not certified "
        r"(Sec.~\ref{sec:threats}).",
        "tab:gumbel",
        "llrrrr",
        r"fixture & engine & $\mu$ & $\beta$ & $q_{10^{-9}}$ & max",
        rows,
    )


def legal_macros(timing, rust):
    """Prose macros for the two-tier bound (skipped when legal_worst is absent)."""
    if "legal_worst" not in timing or "search_00" not in timing:
        print("legal_worst absent -- skipping legal macros")
        return
    lw = timing["legal_worst"]
    un = timing["search_00"]
    c = rust["legal_worst"]["counters"]
    kbar = c["sum_neighbors"] / c["points_processed"]
    lw_cpp = max(lw["cpp"]["samples_ms"])
    lw_rust = max(lw["rust"]["samples_ms"])
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\legalWorstMaxCpp}}{{{lw_cpp:.1f}}}",
        rf"\newcommand{{\legalWorstMaxRust}}{{{lw_rust:.1f}}}",
        rf"\newcommand{{\legalWorstKbar}}{{{kbar:.1f}}}",
        rf"\newcommand{{\legalWorstRatioRust}}{{{max(un['rust']['samples_ms']) / lw_rust:.1f}}}",
        rf"\newcommand{{\legalWorstRatioCpp}}{{{max(un['cpp']['samples_ms']) / lw_cpp:.1f}}}",
    ]
    if "legal_osc" in timing:
        lo = timing["legal_osc"]
        oc = rust["legal_osc"]["counters"]
        macros += [
            rf"\newcommand{{\legalOscMaxCpp}}{{{max(lo['cpp']['samples_ms']):.1f}}}",
            rf"\newcommand{{\legalOscMaxRust}}{{{max(lo['rust']['samples_ms']):.1f}}}",
            rf"\newcommand{{\legalOscKbar}}{{{oc['sum_neighbors'] / oc['points_processed']:.1f}}}",
        ]
    (OUT / "legal_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/legal_macros.tex")


def realdata():
    """Operational-envelope table + macros from the real-drive capture (skipped if absent)."""
    rj = DATA / "realdata.json"
    if not rj.exists():
        print("realdata absent -- skipping operational-envelope outputs")
        return
    allframes = json.loads(rj.read_text())["frames"]
    timing = json.loads((DATA / "wcet.json").read_text())["fixtures"]
    # Envelope rows use the on-map frames (the vehicle leaves the benchmark's cropped map for
    # most of the 57-min bag); P and max-K contract checks use ALL frames.
    frames = [f for f in allframes if f["counters"]["sum_neighbors"] > 0]

    def series(f):
        return sorted(f(x) for x in frames)

    p = sorted(x["n_source"] for x in allframes)
    it = series(lambda x: x["iteration_num"])
    kbar = series(
        lambda x: x["counters"]["sum_neighbors"] / max(x["counters"]["points_processed"], 1)
    )
    kmax = sorted(x["counters"]["max_neighbors"] for x in allframes)
    kd = series(
        lambda x: x["counters"]["kd_nodes_visited"] / max(x["counters"]["points_processed"], 1)
    )
    cpp = series(lambda x: x["cpp_ms"])
    rust = series(lambda x: x["rust_ms"])
    match = sum(1 for x in allframes if x["match"])

    rows = []
    for label, xs, fmt in (
        (r"$P$ (points)", p, "{:.0f}"),
        (r"$N_{\mathrm{iter}}$", it, "{:.0f}"),
        (r"$\bar{K}$ (mean neighbors/pt)", kbar, "{:.2f}"),
        (r"max $K$ (per point)", kmax, "{:.0f}"),
        (r"kd nodes / pt", kd, "{:.1f}"),
        (r"C++ align (\si{ms})", cpp, "{:.2f}"),
        (r"Rust align (\si{ms})", rust, "{:.2f}"),
    ):
        rows.append(
            f"{label} & {fmt.format(pct(xs, 0.5))} & {fmt.format(pct(xs, 0.99))} "
            f"& {fmt.format(xs[-1])}"
        )
    write(
        "realdata.tex",
        rf"Real-data replay (İstanbul urban drive, open-loop frozen guess track): "
        r"per-frame distributions.",
        "tab:realdata",
        "lrrr",
        r"metric & p50 & p99 & max",
        rows,
        note=rf"$P$ and max $K$ over all \num{{{len(allframes)}}} frames; other rows over the "
        rf"\num{{{len(frames)}}} on-map frames. Equal work: \num{{{match}}}/\num{{{len(allframes)}}}.",
    )

    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\realFrames}}{{\num{{{len(allframes)}}}}}",
        rf"\newcommand{{\realOnMap}}{{{len(frames)}}}",
        rf"\newcommand{{\realMatch}}{{\num{{{match}}}}}",
        rf"\newcommand{{\realMatchPct}}{{{100.0 * match / len(allframes):.1f}}}",
        rf"\newcommand{{\realIterMax}}{{{it[-1]}}}",
        rf"\newcommand{{\realKmaxMax}}{{{kmax[-1]}}}",
        rf"\newcommand{{\realPMax}}{{{p[-1]}}}",
        rf"\newcommand{{\realRustMax}}{{{rust[-1]:.1f}}}",
        rf"\newcommand{{\realCppMax}}{{{cpp[-1]:.1f}}}",
    ]
    if "legal_worst" in timing and "search_00" in timing:
        lw = max(timing["legal_worst"]["rust"]["samples_ms"])
        un = max(timing["search_00"]["rust"]["samples_ms"])
        macros += [
            rf"\newcommand{{\realMarginDeploy}}{{{lw / rust[-1]:.1f}}}",
            rf"\newcommand{{\realMarginEngine}}{{{un / rust[-1]:.0f}}}",
        ]
    (OUT / "realdata_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/realdata_macros.tex")


def linfit(xs, ys):
    """Least-squares y = m*x + b; returns (m, b, r2)."""
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    m = sxy / sxx
    b = my - m * mx
    ss_res = sum((y - (m * x + b)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys)
    return m, b, 1.0 - (ss_res / ss_tot if ss_tot > 0 else 0.0)


def psweep():
    """P-sweep table + pgfplots figure + prose macros (skipped if the data is absent)."""
    tj = DATA / "wcet_psweep.json"
    rj = DATA / "psweep_rust.json"
    if not (tj.exists() and rj.exists()):
        print("psweep data absent -- skipping psweep outputs")
        return
    timing = json.loads(tj.read_text())["fixtures"]
    rust = json.loads(rj.read_text())["fixtures"]
    names = sorted(timing, key=lambda n: rust[n]["n_source"])
    ps = [rust[n]["n_source"] for n in names]

    # Work-invariance check: sum_neighbors == P * 64 * 31 at every P.
    for n in names:
        c = rust[n]["counters"]
        assert c["sum_neighbors"] == rust[n]["n_source"] * 64 * 31, n
        assert rust[n]["iteration_num"] == 30, n

    stats = {}  # engine -> (p50s, maxs)
    for eng in ("cpp", "rust"):
        p50s, maxs = [], []
        for n in names:
            xs = sorted(timing[n][eng]["samples_ms"])
            p50s.append(pct(xs, 0.5))
            maxs.append(xs[-1])
        stats[eng] = (p50s, maxs)

    rows = []
    for i, n in enumerate(names):
        rows.append(
            f"{num(ps[i])} & {stats['cpp'][0][i]:.1f} & {stats['cpp'][1][i]:.1f} "
            f"& {stats['rust'][0][i]:.1f} & {stats['rust'][1][i]:.1f}"
        )
    write(
        "psweep.tex",
        r"$P$-sweep on the union-worst geometry (\si{ms}; work invariance verified: "
        r"$N_{\mathrm{iter}}{=}30$, $\sumnbr = P \cdot 64 \cdot 31$ exactly at every $P$).",
        "tab:psweep",
        "rrrrr",
        r"$P$ & \multicolumn{2}{c}{C++ (p50 / max)} & \multicolumn{2}{c}{Rust (p50 / max)}",
        rows,
    )

    # Fits on the max series (the WCET-relevant one) and p50 for the macros.
    fits = {}
    for eng in ("cpp", "rust"):
        m50, b50, r50 = linfit(ps, stats[eng][0])
        mmx, bmx, rmx = linfit(ps, stats[eng][1])
        fits[eng] = {"m50": m50, "b50": b50, "r50": r50, "mmx": mmx, "bmx": bmx, "rmx": rmx}

    # Prose macros (\psweep...) so the section text never hand-types a number.
    def us_per_pt(m):
        return f"{m * 1000:.0f}"

    pmax_cpp = int((100.0 - fits["cpp"]["bmx"]) / fits["cpp"]["mmx"])
    pmax_rust = int((100.0 - fits["rust"]["bmx"]) / fits["rust"]["mmx"])
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\psweepSlopeCpp}}{{{us_per_pt(fits['cpp']['mmx'])}}}",
        rf"\newcommand{{\psweepSlopeRust}}{{{us_per_pt(fits['rust']['mmx'])}}}",
        rf"\newcommand{{\psweepInterceptCpp}}{{{fits['cpp']['bmx']:.1f}}}",
        rf"\newcommand{{\psweepInterceptRust}}{{{fits['rust']['bmx']:.1f}}}",
        rf"\newcommand{{\psweepRsqCpp}}{{{fits['cpp']['rmx']:.4f}}}",
        rf"\newcommand{{\psweepRsqRust}}{{{fits['rust']['rmx']:.4f}}}",
        rf"\newcommand{{\psweepPmaxCpp}}{{{num(pmax_cpp)}}}",
        rf"\newcommand{{\psweepPmaxRust}}{{{num(pmax_rust)}}}",
        rf"\newcommand{{\psweepPmin}}{{{num(min(ps))}}}",
        rf"\newcommand{{\psweepPmax}}{{{num(max(ps))}}}",
    ]
    (OUT / "psweep_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/psweep_macros.tex")

    # pgfplots figure: max latency vs P, measured points + fitted lines.
    fig_dir = ROOT / "figures"
    fig_dir.mkdir(exist_ok=True)

    def coords(ys):
        return " ".join(f"({p},{y:.2f})" for p, y in zip(ps, ys))

    def fitline(f):
        return f"({min(ps)},{f['mmx'] * min(ps) + f['bmx']:.2f}) ({max(ps)},{f['mmx'] * max(ps) + f['bmx']:.2f})"

    fig = rf"""% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.
\begin{{figure}}[t]
\centering
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\columnwidth, height=0.62\columnwidth,
  xlabel={{source points $P$}}, ylabel={{max align time (ms)}},
  xmin=0, ymin=0, legend pos=north west, legend cell align=left,
  grid=major, tick label style={{font=\footnotesize}}, label style={{font=\footnotesize}},
  legend style={{font=\footnotesize}},
]
\addplot[only marks, mark=square*, color=blue] coordinates {{ {coords(stats['cpp'][1])} }};
\addlegendentry{{C++ (measured max)}}
\addplot[no marks, color=blue, dashed] coordinates {{ {fitline(fits['cpp'])} }};
\addlegendentry{{C++ fit ($R^2={fits['cpp']['rmx']:.4f}$)}}
\addplot[only marks, mark=*, color=red] coordinates {{ {coords(stats['rust'][1])} }};
\addlegendentry{{Rust (measured max)}}
\addplot[no marks, color=red, dashed] coordinates {{ {fitline(fits['rust'])} }};
\addlegendentry{{Rust fit ($R^2={fits['rust']['rmx']:.4f}$)}}
\end{{axis}}
\end{{tikzpicture}}
\caption{{Max align latency vs.\ source-point count $P$ on the union-worst geometry
(work per point held invariant; counters verified). Both engines are affine in $P$.}}
\label{{fig:psweep}}
\end{{figure}}
"""
    (fig_dir / "psweep.tex").write_text(fig, encoding="utf-8")
    print("wrote figures/psweep.tex")

    # Residual report (stdout only): flag a cache knee if the largest relative residual is big.
    for eng in ("cpp", "rust"):
        f = fits[eng]
        res = [
            (p, y - (f["mmx"] * p + f["bmx"])) for p, y in zip(ps, stats[eng][1])
        ]
        worst = max(res, key=lambda t: abs(t[1]))
        print(f"psweep {eng}: slope {f['mmx']*1000:.0f} us/pt, intercept {f['bmx']:.1f} ms, "
              f"R2(max) {f['rmx']:.4f}, worst residual {worst[1]:+.1f} ms at P={worst[0]}")


def main_extra():
    timing = json.loads((DATA / "wcet.json").read_text())["fixtures"]
    rust = json.loads((DATA / "wcet_rust.json").read_text())["fixtures"]
    legal_macros(timing, rust)


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    main()
    main_extra()
    realdata()
    psweep()
