        ata = [[0.0] * k for _ in range(k)]
        atb = [0.0] * k
        for row in rows_:
            x = reg_features(row, nterms)
            t = row[3]
            for i in range(k):
                for j in range(k):
                    ata[i][j] += x[i] * x[j]
