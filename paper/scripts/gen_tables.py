def linfit(xs, ys):
    """Least-squares y = m*x + b; returns (m, b, r2)."""
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    m = sxy / sxx
    b = my - m * mx
    ss_res = sum((y - (m * x + b)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys)
    return m, b, 1.0 - (ss_res / ss_tot if ss_tot > 0 else 0.0)


def psweep():
    """P-sweep table + pgfplots figure + prose macros (skipped if the data is absent)."""
    tj = DATA / "wcet_psweep.json"
    rj = DATA / "psweep_rust.json"
    if not (tj.exists() and rj.exists()):
        print("psweep data absent -- skipping psweep outputs")
        return
    timing = json.loads(tj.read_text())["fixtures"]
    rust = json.loads(rj.read_text())["fixtures"]
    names = sorted(timing, key=lambda n: rust[n]["n_source"])
    ps = [rust[n]["n_source"] for n in names]

    # Work-invariance check: sum_neighbors == P * 64 * 31 at every P.
    for n in names:
        c = rust[n]["counters"]
        assert c["sum_neighbors"] == rust[n]["n_source"] * 64 * 31, n
        assert rust[n]["iteration_num"] == 30, n

    stats = {}  # engine -> (p50s, maxs)
    for eng in ("cpp", "rust"):
        p50s, maxs = [], []
        for n in names:
            xs = sorted(timing[n][eng]["samples_ms"])
            p50s.append(pct(xs, 0.5))
            maxs.append(xs[-1])
        stats[eng] = (p50s, maxs)

    rows = []
    for i, n in enumerate(names):
        rows.append(
            f"{num(ps[i])} & {stats['cpp'][0][i]:.1f} & {stats['cpp'][1][i]:.1f} "
            f"& {stats['rust'][0][i]:.1f} & {stats['rust'][1][i]:.1f}"
        )
    write(
        "psweep.tex",
        r"$P$-sweep on the union-worst geometry (\si{ms}; work invariance verified: "
        r"$N_{\mathrm{iter}}{=}30$, $\sumnbr = P \cdot 64 \cdot 31$ exactly at every $P$).",
        "tab:psweep",
        "rrrrr",
        r"$P$ & \multicolumn{2}{c}{C++ (p50 / max)} & \multicolumn{2}{c}{Rust (p50 / max)}",
        rows,
        note=r"The sweep \emph{regenerates} the union-worst geometry at each $P$; its "
        r"$P{=}2000$ row is a distinct fixture instance from --- and so differs slightly "
        r"from --- the frozen \emph{search-00} of Table~\ref{tab:tails}. Same host and "
        r"protocol as Table~\ref{tab:tails} (Sec.~\ref{sec:evaluation}).",
    )

    # Fits on the max series (the WCET-relevant one) and p50 for the macros.
    fits = {}
    for eng in ("cpp", "rust"):
        m50, b50, r50 = linfit(ps, stats[eng][0])
        mmx, bmx, rmx = linfit(ps, stats[eng][1])
        fits[eng] = {"m50": m50, "b50": b50, "r50": r50, "mmx": mmx, "bmx": bmx, "rmx": rmx}

    # Prose macros (\psweep...) so the section text never hand-types a number.
    def us_per_pt(m):
        return f"{m * 1000:.0f}"

    pmax_cpp = int((100.0 - fits["cpp"]["bmx"]) / fits["cpp"]["mmx"])
    pmax_rust = int((100.0 - fits["rust"]["bmx"]) / fits["rust"]["mmx"])
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\psweepSlopeCpp}}{{{us_per_pt(fits['cpp']['mmx'])}}}",
        rf"\newcommand{{\psweepSlopeRust}}{{{us_per_pt(fits['rust']['mmx'])}}}",
        rf"\newcommand{{\psweepInterceptCpp}}{{{fits['cpp']['bmx']:.1f}}}",
        rf"\newcommand{{\psweepInterceptRust}}{{{fits['rust']['bmx']:.1f}}}",
        rf"\newcommand{{\psweepRsqCpp}}{{{fits['cpp']['rmx']:.4f}}}",
        rf"\newcommand{{\psweepRsqRust}}{{{fits['rust']['rmx']:.4f}}}",
        rf"\newcommand{{\psweepPmaxCpp}}{{{num(pmax_cpp)}}}",
        rf"\newcommand{{\psweepPmaxRust}}{{{num(pmax_rust)}}}",
        rf"\newcommand{{\psweepPmin}}{{{num(min(ps))}}}",
        rf"\newcommand{{\psweepPmax}}{{{num(max(ps))}}}",
    ]
    (OUT / "psweep_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/psweep_macros.tex")

    # pgfplots figure: max latency vs P, measured points + fitted lines.
    fig_dir = ROOT / "figures"
    fig_dir.mkdir(exist_ok=True)

    def coords(ys):
        return " ".join(f"({p},{y:.2f})" for p, y in zip(ps, ys))

    def fitline(f):
        return f"({min(ps)},{f['mmx'] * min(ps) + f['bmx']:.2f}) ({max(ps)},{f['mmx'] * max(ps) + f['bmx']:.2f})"

    fig = rf"""% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.
\begin{{figure}}[t]
\centering
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\columnwidth, height=0.62\columnwidth,
  xlabel={{source points $P$}}, ylabel={{max align time (ms)}},
  xmin=0, ymin=0, legend pos=north west, legend cell align=left,
  grid=major, tick label style={{font=\footnotesize}}, label style={{font=\footnotesize}},
  legend style={{font=\footnotesize}},
]
\addplot[only marks, mark=square*, color=blue] coordinates {{ {coords(stats['cpp'][1])} }};
\addlegendentry{{C++ (measured max)}}
\addplot[no marks, color=blue, dashed] coordinates {{ {fitline(fits['cpp'])} }};
\addlegendentry{{C++ fit ($R^2={fits['cpp']['rmx']:.4f}$)}}
\addplot[only marks, mark=*, color=red] coordinates {{ {coords(stats['rust'][1])} }};
\addlegendentry{{Rust (measured max)}}
\addplot[no marks, color=red, dashed] coordinates {{ {fitline(fits['rust'])} }};
\addlegendentry{{Rust fit ($R^2={fits['rust']['rmx']:.4f}$)}}
\end{{axis}}
\end{{tikzpicture}}
\caption{{Max align latency vs.\ source-point count $P$ on the union-worst geometry
(work per point held invariant; counters verified). Both engines are affine in $P$.}}
\label{{fig:psweep}}
\end{{figure}}
"""
    (fig_dir / "psweep.tex").write_text(fig, encoding="utf-8")
    print("wrote figures/psweep.tex")

    # Residual report (stdout only): flag a cache knee if the largest relative residual is big.
    for eng in ("cpp", "rust"):
        f = fits[eng]
        res = [
            (p, y - (f["mmx"] * p + f["bmx"])) for p, y in zip(ps, stats[eng][1])
        ]
        worst = max(res, key=lambda t: abs(t[1]))
        print(f"psweep {eng}: slope {f['mmx']*1000:.0f} us/pt, intercept {f['bmx']:.1f} ms, "
              f"R2(max) {f['rmx']:.4f}, worst residual {worst[1]:+.1f} ms at P={worst[0]}")


