    for eng in ("cpp", "rust"):
        f = fits[eng]
        res = [
            (p, y - (f["mmx"] * p + f["bmx"])) for p, y in zip(ps, stats[eng][1])
        ]
        worst = max(res, key=lambda t: abs(t[1]))
        print(f"psweep {eng}: slope {f['mmx']*1000:.0f} us/pt, intercept {f['bmx']:.1f} ms, "
              f"R2(max) {f['rmx']:.4f}, worst residual {worst[1]:+.1f} ms at P={worst[0]}")


