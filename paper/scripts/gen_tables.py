def ulp_tex(v):
    """Render a ULP count for prose: exact when small, mantissa*10^e when large."""
    v = int(v)
    if v < 10000:
        return str(v)
    import math as _m
    e = int(_m.floor(_m.log10(v)))
    return rf"{v / 10 ** e:.1f}\times 10^{{{e}}}"


def subnormal_ab():
    """Subnormal shell A/B macros from data/subnormal_ab.json (C5, Isolated): the \\oneoffShell*
    p50 times, re-measured on-protocol from the reproducible subnormal / subnormal_ctrl fixtures.
    Guard (regenerate-or-break): moving out of the subnormal band must NOT reduce the time (the
    control is >= the in-band shell), so the "subnormals are not the mechanism" null holds."""
    aj = DATA / "subnormal_ab.json"
    if not aj.exists():
        print("subnormal_ab absent -- skipping shell A/B macros")
        return
    doc = json.loads(aj.read_text())
    fx = doc["fixtures"]

    def p50(name, eng):
        return pct(sorted(fx[name][eng]["samples_ms"]), 0.5)

    sub_cpp, ctrl_cpp = p50("subnormal", "cpp"), p50("subnormal_ctrl", "cpp")
    sub_rust, ctrl_rust = p50("subnormal", "rust"), p50("subnormal_ctrl", "rust")
    # The null test: removing subnormals (the control) must not be faster than the in-band shell.
