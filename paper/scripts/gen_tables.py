def parallel():
    """C8 parallel-feasibility table + macros from data/parallel.json (skipped if absent).

    Guards (regenerate-or-break): the Rust deployment witness must fit the 100 ms budget at
    the k the prose names, and Rust must scale (k=4 speedup > 1.5x) so the "closes the gap"
    claim cannot go stale.
    """
    pj = DATA / "parallel.json"
    if not pj.exists():
        print("parallel data absent -- skipping C8 outputs")
        return
    doc = json.loads(pj.read_text())
    inputs = doc["inputs"]
    label = {"search_00": r"\emph{search-00}", "legal_worst": r"\emph{legal-worst}",
             "legal_osc": r"\emph{legal-osc}$^\dagger$"}
    rows = []
    for fx in ("legal_worst",):
        cells = inputs[fx]
        for eng, name in (("cpp", "C++"), ("rust", "Rust")):
            r = [cells[str(k)][eng] for k in (1, 2, 4)]
            rows.append(
                f"{label[fx] if eng == 'cpp' else ''} & {name} & "
                f"{r[0]['max_ms']:.1f} & {r[1]['max_ms']:.1f} ({r[1]['speedup_max']:.1f}$\\times$) "
                f"& {r[2]['max_ms']:.1f} ({r[2]['speedup_max']:.1f}$\\times$)"
            )
    write(
        "parallel.tex",
        r"Host parallel feasibility for the deployment-tier witness (maximum align \si{ms}; "
        r"one pinned worker per isolated physical core). Not a multi-core WCET result.",
        "tab:parallel",
        "llrrr",
        r"fixture & engine & $k{=}1$ & $k{=}2$ & $k{=}4$",
        rows,
        note=r"Rust iteration counts are $k$-invariant; calibration drift: "
        r"\parCalibDriftPct\% (no throttling).",
    )
    lw = inputs["legal_worst"]
    # First k at which the Rust deployment witness fits the 100 ms budget.
    fit_k = next((k for k in (1, 2, 4) if lw[str(k)]["rust"]["max_ms"] < 100.0), None)
    if fit_k is None:
        raise SystemExit("parallel: Rust legal-worst never fits 100 ms in {1,2,4} -- the "
                         "Sec. V-parallel 'closes the gap' claim is stale; update the prose")
    if inputs["search_00"]["4"]["rust"]["speedup_max"] < 1.5:
        raise SystemExit("parallel: Rust k=4 speedup < 1.5x -- the scaling claim is stale")
    macros = [
        "% AUTO-GENERATED by scripts/gen_tables.py -- do not hand-edit.",
        rf"\newcommand{{\parCalibDriftPct}}{{{doc['meta']['calib_drift_pct']:.1f}}}",
        rf"\newcommand{{\parRustLegalFitK}}{{{fit_k}}}",
        rf"\newcommand{{\parRustLegalFitMaxMs}}{{{lw[str(fit_k)]['rust']['max_ms']:.1f}}}",
        rf"\newcommand{{\parRustLegalSerialMs}}{{{lw['1']['rust']['max_ms']:.1f}}}",
        rf"\newcommand{{\parRustSpeedupFour}}{{{inputs['search_00']['4']['rust']['speedup_max']:.1f}}}",
        rf"\newcommand{{\parCppSpeedupFour}}{{{inputs['search_00']['4']['cpp']['speedup_max']:.1f}}}",
        rf"\newcommand{{\parRustLegalSpeedupFour}}{{{lw['4']['rust']['speedup_max']:.1f}}}",
    ]
    (OUT / "parallel_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print("wrote tables/parallel.tex + parallel_macros.tex")


