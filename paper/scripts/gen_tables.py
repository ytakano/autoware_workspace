def ulp_tex(v):
    """Render a ULP count for prose: exact when small, mantissa*10^e when large."""
    v = int(v)
    if v < 10000:
        return str(v)
    import math as _m
    e = int(_m.floor(_m.log10(v)))
    return rf"{v / 10 ** e:.1f}\times 10^{{{e}}}"


